import type { Rng } from './seed';

export type Pt = { x: number; y: number };
/** [tagIn, ...points, tagOut] */
export type GlyphPath = Array<number | Pt>;
export type Adjust = (ip: GlyphPath, pc: number, nc: number, n: number, rng: Rng) => void;
export type Glyph = {
	advance: number;
	options: GlyphPath[];
	marks: GlyphPath[][] | null;
	adjust: Adjust;
};
export type PickedGlyph = {
	path: GlyphPath;
	marks: GlyphPath[];
	advance: number;
	index: number;
	adjust: Adjust;
};

function P(tagIn: number, xy: number[], tagOut: number): GlyphPath {
	const pts: GlyphPath = [];
	for (let i = 0; i < xy.length; i += 2) pts.push({ x: xy[i], y: xy[i + 1] });
	return [tagIn, ...pts, tagOut];
}

function copyPath(path: GlyphPath): GlyphPath {
	return path.map((el) => (typeof el === 'number' ? el : { x: el.x, y: el.y }));
}

function G(
	advance: number,
	options: GlyphPath[],
	extra: { marks?: GlyphPath[][]; adjust?: Adjust } = {},
): Glyph {
	return { advance, options, marks: extra.marks ?? null, adjust: extra.adjust ?? defaultAdjust };
}

function last(ip: GlyphPath): Pt {
	return ip[ip.length - 2] as Pt;
}

function defaultAdjust(ip: GlyphPath, pc: number, nc: number): void {
	const start = ip[0];
	const end = ip[ip.length - 1];
	if (pc === 1 && start === 3) {
		ip.splice(1, 0, { x: (ip[1] as Pt).x - 0.05, y: 0.98 });
		ip[0] = 1;
	} else if (pc === 2 && start === 3) {
		ip.splice(1, 0, { x: (ip[1] as Pt).x - 0.04, y: 0.86 });
		ip[0] = 2;
	}
	if (nc === 3 && end === 1) {
		const l = last(ip);
		ip[ip.length - 2] = { x: l.x + 0.06, y: 0.78 };
		ip[ip.length - 1] = 2;
	} else if (nc === 1 && end === 3) {
		ip.splice(-1, 0, { x: last(ip).x + 0.08, y: 0.96 });
		ip[ip.length - 1] = 1;
	}
}

