// --- diacritics: a base letter with a mark over it ---

const MARKS: Record<'acute' | 'dieresis' | 'tilde', (cx: number) => GlyphPath[]> = {
	acute: (cx) => [P(0, [cx - 0.06, 0.42, cx + 0.06, 0.3], 0)],
	dieresis: (cx) => [dot(cx - 0.09, 0.37), dot(cx + 0.09, 0.37)],
	tilde: (cx) => [P(0, [cx - 0.16, 0.42, cx - 0.06, 0.33, cx + 0.06, 0.41, cx + 0.16, 0.32], 0)],
};

type MarkName = keyof typeof MARKS;

const COMPOSED: Record<string, [base: string, mark: MarkName]> = {
	á: ['a', 'acute'],
	é: ['e', 'acute'],
	í: ['i', 'acute'],
	ó: ['o', 'acute'],
	ú: ['u', 'acute'],
	ü: ['u', 'dieresis'],
	ñ: ['n', 'tilde'],
};

function marksOf(glyph: Glyph, n: number): GlyphPath[] {
	if (!glyph.marks) return [];
	const set = glyph.marks[n] ?? glyph.marks[0] ?? [];
	return set.map(copyPath);
}

/** The glyph for a character, or null when the hand doesn't know it. */
export function pickGlyph(letter: string, n: number): PickedGlyph | null {
	const composed = COMPOSED[letter] ?? COMPOSED[letter.toLowerCase()];
	if (composed) {
		const [base, mark] = composed;
		const picked = pickGlyph(base, n);
		if (!picked) return null;
		const cx = picked.advance * 0.42;
		const drawn = MARKS[mark](cx);
		// An accent replaces the i's own dot; it sits over everything else.
		const kept = base === 'i' ? [] : picked.marks;
		return { ...picked, marks: [...kept, ...drawn] };
	}
	// The hand knows few capitals. A missing capital writes as its lowercase
	// shape instead of vanishing from the word.
	const g = GLYPHS[letter] ?? GLYPHS[letter.toLowerCase()];
	if (!g) return null;
	const opts = g.options;
	const idx = ((n % opts.length) + opts.length) % opts.length;
	return {
		path: copyPath(opts[idx]),
		marks: marksOf(g, idx),
		advance: g.advance,
		index: idx,
		adjust: g.adjust,
	};
}

export function glyphCount(letter: string): number {
	const composed = COMPOSED[letter] ?? COMPOSED[letter.toLowerCase()];
	const key = composed ? composed[0] : letter;
	return (GLYPHS[key] ?? GLYPHS[key.toLowerCase()])?.options.length ?? 0;
}
